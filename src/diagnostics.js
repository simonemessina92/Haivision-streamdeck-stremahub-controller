function terminalFields(r={}){
 const fields=['liveStatus','IAPStatus','recordStatus','forwardStatus'];
 const field=fields.find(k=>Number(r[k])<0),code=field?Number(r[field]):Number(r.errorCode)||0;
 const args=String(r[(field||'liveStatus')+'ErrorParam']||'').split(';');
 return {...(Number.isFinite(Number(r.channelStatus??r.status))?{status:Number(r.channelStatus??r.status)}:{}),message:typeof r.message==='string'?r.message:'',errorCode:code,errorParams:r.errorParams||{'param.arg1':args[0],'param.arg2':args[1]}};
}
function diagnostic(item,kind='input'){
 if(!item)return null;
 const r=kind==='input'?{...item,...item.nativeDiagnostic}:item,status=Number(r.status),code=Number(r.errorCode);
 if(kind==='output'&&!r.enabled)return null;
 if(status!==3&&status!==4&&!(kind==='input'&&code<0))return null;
 const severity=status===4?'warning':'error',raw=typeof r.message==='string'?r.message:'';
 const catalog=kind==='output'?STREAMHUB_MESSAGES.output:STREAMHUB_MESSAGES.input;
 let message=kind==='input'&&code<0?STREAMHUB_MESSAGES.terminal[code]||raw:catalog[raw]||raw;
 message=(message||severity.toUpperCase()).replace(/\$\{([^}]+)\}/g,(match,key)=>r.errorParams?.[key]??match);
 return {severity,label:severity.toUpperCase(),message,code:code<0?code:raw||null,status};
}
function chunks(text){
 const lines=[];let line='';
 for(let word of String(text).split(/\s+/)){
  while(word.length>12){if(line){lines.push(line);line='';}lines.push(word.slice(0,12));word=word.slice(12);}
  if(!word)continue;
  if(line&&line.length+word.length+1>12){lines.push(line);line=word;}else line+=(line?' ':'')+word;
 }
 if(line)lines.push(line);
 const result=[];for(let index=0;index<lines.length;index+=4)result.push(lines.slice(index,index+4).join('\n'));
 return result;
}
